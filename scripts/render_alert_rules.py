"""
Generate monitoring/prometheus/alert_rules.yml AND the threshold lines of the Grafana dashboard
from params.yaml (single source of truth for thresholds). `--check` exits 1 if either committed
file is out of date (used in CI).

Alerts labelled action=retrain are routed by Alertmanager to the retrain webhook; everything
else is an operational page (retraining cannot fix a crashed server or a slow network).
"""

import argparse
import sys
from pathlib import Path

import yaml

ROOT = Path(__file__).resolve().parents[1]
OUT = ROOT / "monitoring" / "prometheus" / "alert_rules.yml"
DASHBOARD = ROOT / "monitoring" / "grafana" / "dashboards" / "ddd_main.json"


def render_dashboard(params: dict) -> str:
    """Set the dashboard's constant threshold series (identified by legend) from params.yaml."""
    import json

    lines = {
        "SLO (params.yaml)": f"{params['slo']['p95_latency_s'] * 1000:g}",
        "PSI threshold (params.yaml)": f"{params['drift']['psi_threshold']:g}",
    }
    d = json.loads(DASHBOARD.read_text())
    for panel in d.get("panels", []):
        for t in panel.get("targets", []):
            if t.get("legendFormat") in lines:
                t["expr"] = lines[t["legendFormat"]]
    return json.dumps(d, indent=2) + "\n"


def render(params: dict) -> str:
    slo, drift = params["slo"], params["drift"]
    rules = [
        {
            "alert": "HighPredictionErrorRate",
            "expr": "sum(rate(ddd_prediction_errors_total[5m])) / clamp_min(sum(rate(ddd_predictions_total[5m])), 1e-9)"
            f" > {slo['max_error_ratio']}",
            "for": "2m",
            "labels": {"severity": "critical", "action": "page"},
            "annotations": {
                "summary": "Model calls are failing",
                "description": "{{ $value | humanizePercentage }} of model calls failed over 5m "
                f"(SLO {slo['max_error_ratio']}). Users see state=error, not alert.",
            },
        },
        {
            "alert": "HighInferenceLatency",
            "expr": "histogram_quantile(0.95, sum by (le) (rate(ddd_inference_latency_seconds_bucket[5m])))"
            f" > {slo['p95_latency_s']}",
            "for": "2m",
            "labels": {"severity": "warning", "action": "page"},
            "annotations": {
                "summary": "P95 frame-to-prediction latency above SLO",
                "description": "P95 is {{ $value | humanizeDuration }} (SLO " f"{slo['p95_latency_s']}s).",
            },
        },
        {
            "alert": "DataDriftDetected",
            "expr": f"ddd_overall_drift_score > {drift['psi_threshold']}",
            "for": slo["drift_for"],
            "labels": {"severity": "warning", "action": "retrain"},
            "annotations": {
                "summary": "Live features drifted from the training baseline",
                "description": "Max PSI {{ $value | humanize }} > "
                f"{drift['psi_threshold']} for {slo['drift_for']}. Retraining only "
                "helps if new labelled data has been added.",
            },
        },
        {
            "alert": "ModelNotLoaded",
            "expr": "ddd_model_loaded == 0",
            "for": "2m",
            "labels": {"severity": "critical", "action": "page"},
            "annotations": {"summary": "Model server has no model loaded (all predictions fail)"},
        },
        {
            "alert": "DriftBaselineMissing",
            "expr": "ddd_drift_baseline_loaded == 0",
            "for": "10m",
            "labels": {"severity": "warning", "action": "page"},
            "annotations": {"summary": "Backend could not load the champion's drift baseline; drift is unmonitored"},
        },
        {
            "alert": "ModelServerDown",
            "expr": 'up{job="ddd_model_server"} == 0',
            "for": "1m",
            "labels": {"severity": "critical", "action": "page"},
            "annotations": {"summary": "Model server is unreachable"},
        },
        {
            "alert": "BackendDown",
            "expr": 'up{job="ddd_backend"} == 0',
            "for": "1m",
            "labels": {"severity": "critical", "action": "page"},
            "annotations": {"summary": "Backend API is unreachable"},
        },
    ]
    header = (
        "# GENERATED by scripts/render_alert_rules.py from params.yaml — do not edit by hand.\n"
        "# Regenerate: python scripts/render_alert_rules.py   (CI runs it with --check)\n"
    )
    return header + yaml.safe_dump(
        {"groups": [{"name": "ddd_alerts", "interval": "15s", "rules": rules}]}, sort_keys=False, width=120
    )


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument("--check", action="store_true")
    args = ap.parse_args()
    params = yaml.safe_load((ROOT / "params.yaml").read_text())
    outputs = {OUT: render(params), DASHBOARD: render_dashboard(params)}
    if args.check:
        stale = [str(p.relative_to(ROOT)) for p, text in outputs.items() if not p.exists() or p.read_text() != text]
        if stale:
            print(f"out of date with params.yaml: {stale}; run: python scripts/render_alert_rules.py")
            sys.exit(1)
        print("alert rules and dashboard thresholds match params.yaml")
        return
    for p, text in outputs.items():
        p.write_text(text)
        print(f"wrote {p.relative_to(ROOT)}")


if __name__ == "__main__":
    main()
